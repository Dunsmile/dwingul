function makeOptions(rows, index) {
  const answer = Array.isArray(rows[index]) ? rows[index][0] : rows[index];
  const initial = hangulInitials(answer);
  const wrong = [];
  for (let offset = 1; wrong.length < 3 && offset < rows.length; offset += 1) {
    const candidate = Array.isArray(rows[(index + offset) % rows.length]) ? rows[(index + offset) % rows.length][0] : rows[(index + offset) % rows.length];
    if (candidate !== answer && hangulInitials(candidate) !== initial && !wrong.includes(candidate)) wrong.push(candidate);
  }
  const options = [...wrong];
  const answerIndex = index % 4;
  options.splice(answerIndex, 0, answer);
  return { options, answerIndex };
}

function buildDrama(title, index) {
  const initials = hangulInitials(title);
  const { options, answerIndex } = makeOptions(dramaRows, index);
  return {
    id: `guess-drama-${String(index + 1).padStart(3, "0")}`,
    category: "drama",
    prompt: `드라마 제목 초성 · ${initials}\n이 제목은 무엇일까요?`,
    options,
    answer: answerIndex,
    explain: `정답은 《${title}》입니다.`,
    initials,
    canonicalAnswer: title,
    source: "https://www.netflix.com/kr/browse/genre/2638104",
  };
}

function buildCharacter(category, row, index, rows) {
  const [name, work] = row;
  const initials = hangulInitials(name);
  const { options, answerIndex } = makeOptions(rows, index);
  return {
    id: `guess-${category}-${String(index + 1).padStart(3, "0")}`,
    category,
    prompt: `${category === "anime" ? "애니" : "게임"} 《${work}》 캐릭터 · 초성 ${initials}\n누구일까요?`,
    options,
    answer: answerIndex,
    explain: `정답은 《${work}》의 ${name}입니다.`,
    initials,
    canonicalAnswer: name,
    source: WORK_SOURCES[work],
  };
}

export const guessBank = [
  ...dramaRows.map(buildDrama),
  ...animeRows.map((row, index) => buildCharacter("anime", row, index, animeRows)),
  ...gameRows.map((row, index) => buildCharacter("game", row, index, gameRows)),
];
