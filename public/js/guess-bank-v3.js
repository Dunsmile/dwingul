const CHOSEONG = ["ㄱ", "ㄲ", "ㄴ", "ㄷ", "ㄸ", "ㄹ", "ㅁ", "ㅂ", "ㅃ", "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅉ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"];

/** Return the visible initial clue for the spelling supplied to the player. */
export function hangulInitials(value) {
  return String(value ?? "")
    .normalize("NFC")
    .split("")
    .map((character) => {
      const code = character.charCodeAt(0);
      if (code >= 0xac00 && code <= 0xd7a3) return CHOSEONG[Math.floor((code - 0xac00) / 588)];
      return character;
    })
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}

